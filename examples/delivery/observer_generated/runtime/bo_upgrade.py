"""Plan and apply a versioned runtime copy without overwriting local changes.

Project workflows, queries and personal files are never generated by this tool.
After upgrading, regenerate the model and run the project's normal verification.
"""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import uuid

try:
    from .behavior_model import contained, read
    from .sync_io import write
except ImportError:
    from behavior_model import contained, read
    from sync_io import write

RELEASE = '2026.10-implementation-coverage'
PROTOCOLS = {'behavior': 3, 'event': 3, 'activity': 'activity-graph/v1',
             'export': 'bo-stategraph/v1', 'recording': 1, 'runtime_frames': 1, 'preferences': 1,
             'implementation': 'bo-implementation/v1'}
CORE = {'bo_stategraph.py': '__init__.py', 'bo_contracts.py': 'bo_contracts.py',
        'execution_contract.py': 'execution_contract.py'}


def bridge_source(name, module='bo_stategraph'):
    target = module.replace('/', '.') + ('' if name == 'bo_stategraph.py' else '.' + name[:-3])
    return ('''"""Compatibility entry; implementation belongs to the independent state module."""
try:
    from .bo_runtime import resolve
except ImportError:
    from bo_runtime import resolve

_core = resolve(__file__, __name__, TARGET)
globals().update({k: v for k, v in vars(_core).items() if not k.startswith('__')})
if __name__ == '__main__' and hasattr(_core, 'main'):
    _core.main()
'''.replace('TARGET', repr(target))).encode('utf-8')


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def plan(root, *, runtime, module='bo_stategraph', viewers=(), baseline=None, source=None):
    root = Path(root).resolve()
    source = Path(source or Path(__file__).resolve().parent)
    if not module.isidentifier():
        raise ValueError('module must be one Python package name')
    if not root.is_dir():
        raise ValueError('project root does not exist')
    metadata = contained(root, module + '/runtime-version.json')
    previous = read(metadata) if metadata.exists() else {}
    if previous and previous.get('schema') != 1:
        raise ValueError('unsupported runtime manifest; migrate explicitly')
    if any(previous.get('protocols', {}).get(k, v) != v for k, v in PROTOCOLS.items()):
        raise ValueError('protocol version differs; migrate artifacts before copying runtime')
    known = dict(previous.get('files', {}))
    if baseline:
        known.update({k: v for k, v in read(contained(root, baseline))['files'].items() if v})
    sources = {runtime + '/' + path.name: path for path in source.glob('*.py')}
    sources.update({runtime + '/' + name: bridge_source(name, module) for name in CORE})
    sources.update({module + '/' + target: source / name for name, target in CORE.items()})
    for viewer in viewers:
        sources.update({viewer + '/' + path.name: path for path in (source.parent / 'assets/stategraph-viewer').iterdir() if path.is_file()})
    files, conflicts, changes = {}, [], []
    for name, original in sorted(sources.items()):
        target = contained(root, name)
        expected = hashlib.sha256(original).hexdigest() if isinstance(original, bytes) else sha(original)
        current = sha(target) if target.exists() else None
        files[name] = expected
        if current != expected:
            if current is not None and known.get(name) != current:
                conflicts.append(name)
            else:
                changes.append(name)
    return {'valid': not conflicts, 'release': RELEASE, 'protocols': PROTOCOLS,
            'files': files, 'changes': changes, 'conflicts': conflicts,
            'retained_legacy_files': sorted(set(previous.get('files', {})) - set(files)),
            'metadata': metadata, 'sources': sources}


def apply(root, **options):
    root = Path(root).resolve()
    proposed = plan(root, **options)
    if not proposed['valid']:
        raise ValueError('local runtime edits need reconciliation: ' + ', '.join(proposed['conflicts']))
    backup = root / '.stategraph/upgrades' / uuid.uuid4().hex
    written = []
    try:
        for name in proposed['changes']:
            target = contained(root, name)
            if target.exists():
                saved = backup / name
                saved.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(target, saved)
            target.parent.mkdir(parents=True, exist_ok=True)
            written.append(name)
            original = proposed['sources'][name]
            if isinstance(original, bytes): target.write_bytes(original)
            else: shutil.copyfile(original, target)
        value = {key: proposed[key] for key in ('release', 'protocols', 'files', 'retained_legacy_files')}
        write(proposed['metadata'], {'schema': 1, **value})
    except Exception:
        for name in reversed(written):
            target, saved = contained(root, name), backup / name
            if saved.exists(): shutil.copyfile(saved, target)
            elif target.exists(): target.unlink()
        raise
    return {key: proposed[key] for key in ('valid', 'release', 'protocols', 'changes', 'conflicts', 'retained_legacy_files')}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=['plan', 'apply'])
    parser.add_argument('--root', required=True)
    parser.add_argument('--runtime', required=True)
    parser.add_argument('--module', default='bo_stategraph')
    parser.add_argument('--viewer', action='append', default=[])
    parser.add_argument('--baseline', help='Preserved change_sync baseline for first migration')
    parser.add_argument('--source', help='Canonical Skill scripts directory, if this is a copied tool')
    args = parser.parse_args()
    options = dict(runtime=args.runtime, module=args.module, viewers=args.viewer, baseline=args.baseline, source=args.source)
    result = apply(args.root, **options) if args.command == 'apply' else plan(args.root, **options)
    print(json.dumps({k: v for k, v in result.items() if k not in ('metadata', 'sources', 'files')}, ensure_ascii=False))
    return 0 if result['valid'] else 1


if __name__ == '__main__':
    raise SystemExit(main())
